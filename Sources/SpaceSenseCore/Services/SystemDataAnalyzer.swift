import Foundation

public actor SystemDataAnalyzer {
    private struct ProbeSpec {
        let category: String
        let relativeOrAbsolutePath: String
        let isHomeRelative: Bool
        let explanation: String
        let recommendation: CleanupRecommendationLevel
        let potentialRisks: String
        let isUserCleanable: Bool
    }

    private struct CachedProbeResult {
        let timestamp: Date
        let size: Int64
        let hadPermissionIssue: Bool
        let wasTruncated: Bool
    }

    private var probeCache: [String: CachedProbeResult] = [:]

    public init() {}

    public func analyze(
        volumeStats: VolumeStats,
        knownScanBytes: Int64? = nil,
        customHomeURL: URL? = nil,
        maxFilesPerLocation: Int = 35_000,
        premeasuredDirectorySizes: [String: Int64] = [:],
        useCachedProbes: Bool = false
    ) async -> SystemDataReport {
        let home = (customHomeURL ?? FileManager.default.homeDirectoryForCurrentUser).path
        let specs: [ProbeSpec] = [
            ProbeSpec(
                category: "User Application Caches",
                relativeOrAbsolutePath: "Library/Caches",
                isHomeRelative: true,
                explanation: "Temporary cached data stored by macOS apps and browsers to speed up loading.",
                recommendation: .recommended,
                potentialRisks: "Apps may take slightly longer to launch or re-download cached assets once after removal.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "Application & Diagnostic Logs",
                relativeOrAbsolutePath: "Library/Logs",
                isHomeRelative: true,
                explanation: "Diagnostic, crash, and activity logs written by user applications.",
                recommendation: .recommended,
                potentialRisks: "Historical crash logs for debugging past app issues will be moved to Trash.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "Xcode DerivedData",
                relativeOrAbsolutePath: "Library/Developer/Xcode/DerivedData",
                isHomeRelative: true,
                explanation: "Intermediate build artifacts, indexes, and module caches generated by Xcode.",
                recommendation: .recommended,
                potentialRisks: "Safe to remove; your next Xcode build will perform a clean rebuild.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "Xcode Archives & Device Support",
                relativeOrAbsolutePath: "Library/Developer/Xcode/Archives",
                isHomeRelative: true,
                explanation: "Archived release builds and dSYM bundles created for App Store submission or distribution.",
                recommendation: .reviewCarefully,
                potentialRisks: "Removing archives prevents symbolication of crash reports for those specific historical builds.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "Simulator Runtimes & Devices",
                relativeOrAbsolutePath: "Library/Developer/CoreSimulator",
                isHomeRelative: true,
                explanation: "iOS, watchOS, and tvOS simulator device states, installed test apps, and caches.",
                recommendation: .reviewCarefully,
                potentialRisks: "Deleting simulator data resets simulator app state and saved test data.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "iOS & iPadOS Device Backups",
                relativeOrAbsolutePath: "Library/Application Support/MobileSync/Backup",
                isHomeRelative: true,
                explanation: "Local Finder backups of iPhones and iPads synced with this Mac.",
                recommendation: .reviewCarefully,
                potentialRisks: "Do not delete unless you have an up-to-date iCloud backup or no longer need older device backups.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "Application Support Data",
                relativeOrAbsolutePath: "Library/Application Support",
                isHomeRelative: true,
                explanation: "Databases, plugins, offline assets, and configuration data used by installed applications.",
                recommendation: .reviewCarefully,
                potentialRisks: "Contains active app settings, local databases, and project assets. Only remove folders for uninstalled apps.",
                isUserCleanable: false
            ),
            ProbeSpec(
                category: "Sandboxed App Containers",
                relativeOrAbsolutePath: "Library/Containers",
                isHomeRelative: true,
                explanation: "Sandboxed storage containers for Mac App Store and system applications.",
                recommendation: .doNotModify,
                potentialRisks: "Modifying container internals directly can corrupt app preferences or local document databases.",
                isUserCleanable: false
            ),
            ProbeSpec(
                category: "Homebrew & Package Caches",
                relativeOrAbsolutePath: "Library/Caches/Homebrew",
                isHomeRelative: true,
                explanation: "Downloaded bottles and source tarballs cached by Homebrew.",
                recommendation: .recommended,
                potentialRisks: "Low risk; Homebrew will re-download package archives only if reinstalling an older bottle.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "System-Wide Library Caches",
                relativeOrAbsolutePath: "/Library/Caches",
                isHomeRelative: false,
                explanation: "Shared system-level caches accessible across user accounts.",
                recommendation: .reviewCarefully,
                potentialRisks: "Some system helpers may require administrator privileges or restart to rebuild caches.",
                isUserCleanable: false
            ),
            ProbeSpec(
                category: "System Temporary Files",
                relativeOrAbsolutePath: "/private/var/tmp",
                isHomeRelative: false,
                explanation: "Temporary scratch files written by system processes and command-line tools.",
                recommendation: .reviewCarefully,
                potentialRisks: "Do not remove files actively in use by running background tasks.",
                isUserCleanable: true
            ),
            ProbeSpec(
                category: "Protected macOS System Volume",
                relativeOrAbsolutePath: "/System/Library",
                isHomeRelative: false,
                explanation: "Cryptographically sealed macOS operating system frameworks, kernels, and assets (SIP protected).",
                recommendation: .doNotModify,
                potentialRisks: "Protected by System Integrity Protection (SIP) and read-only APFS snapshot; never modify.",
                isUserCleanable: false
            )
        ]

        var items: [SystemDataItem] = []
        var totalMeasured: Int64 = 0
        var restrictedCount = 0

        for spec in specs {
            if Task.isCancelled { break }
            let fullPath = spec.isHomeRelative
                ? URL(fileURLWithPath: home).appendingPathComponent(spec.relativeOrAbsolutePath).path
                : spec.relativeOrAbsolutePath
            let url = URL(fileURLWithPath: fullPath)

            var isDir: ObjCBool = false
            let exists = FileManager.default.fileExists(atPath: fullPath, isDirectory: &isDir)

            if !exists {
                items.append(
                    SystemDataItem(
                        category: spec.category,
                        locationPath: fullPath,
                        url: nil,
                        sizeBytes: 0,
                        measurability: .measured,
                        explanation: spec.explanation + " (Not present on this Mac.)",
                        recommendation: spec.recommendation,
                        potentialRisks: spec.potentialRisks,
                        isUserCleanable: false
                    )
                )
                continue
            }

            let readable = FileManager.default.isReadableFile(atPath: fullPath)
            if !readable {
                restrictedCount += 1
                items.append(
                    SystemDataItem(
                        category: spec.category,
                        locationPath: fullPath,
                        url: url,
                        sizeBytes: nil,
                        measurability: .restricted,
                        explanation: spec.explanation + " Access requires Full Disk Access permission in macOS System Settings.",
                        recommendation: .doNotModify,
                        potentialRisks: spec.potentialRisks,
                        isUserCleanable: false
                    )
                )
                continue
            }

            if fullPath == "/System/Library" {
                items.append(
                    SystemDataItem(
                        category: spec.category,
                        locationPath: fullPath,
                        url: url,
                        sizeBytes: nil,
                        measurability: .restricted,
                        explanation: spec.explanation,
                        recommendation: .doNotModify,
                        potentialRisks: spec.potentialRisks,
                        isUserCleanable: false
                    )
                )
                continue
            }

            // Avoid double-counting child probes inside parent probes
            let excludedSubpath: String?
            if spec.relativeOrAbsolutePath == "Library/Caches" {
                excludedSubpath = StorageScanner.fastCleanPath(URL(fileURLWithPath: home).appendingPathComponent("Library/Caches/Homebrew").standardizedFileURL.path)
            } else if spec.relativeOrAbsolutePath == "Library/Application Support" {
                excludedSubpath = StorageScanner.fastCleanPath(URL(fileURLWithPath: home).appendingPathComponent("Library/Application Support/MobileSync/Backup").standardizedFileURL.path)
            } else {
                excludedSubpath = nil
            }

            let cleanedFullPath = StorageScanner.fastCleanPath(url.standardizedFileURL.path)
            let size: Int64
            let hadPermissionIssue: Bool
            let wasTruncated: Bool

            if let premeasured = premeasuredDirectorySizes[cleanedFullPath] {
                let subtracted = excludedSubpath.flatMap { premeasuredDirectorySizes[$0] } ?? 0
                size = max(0, premeasured - subtracted)
                hadPermissionIssue = false
                wasTruncated = false
                probeCache[cleanedFullPath] = CachedProbeResult(
                    timestamp: Date(),
                    size: size,
                    hadPermissionIssue: false,
                    wasTruncated: false
                )
            } else if useCachedProbes,
                      let cached = probeCache[cleanedFullPath],
                      Date().timeIntervalSince(cached.timestamp) < 120 {
                size = cached.size
                hadPermissionIssue = cached.hadPermissionIssue
                wasTruncated = cached.wasTruncated
            } else {
                let measured = await measureDirectoryBytes(
                    at: url,
                    maxFiles: maxFilesPerLocation,
                    excludingSubpath: excludedSubpath
                )
                size = measured.0
                hadPermissionIssue = measured.1
                wasTruncated = measured.2
                probeCache[cleanedFullPath] = CachedProbeResult(
                    timestamp: Date(),
                    size: size,
                    hadPermissionIssue: hadPermissionIssue,
                    wasTruncated: wasTruncated
                )
            }

            totalMeasured += size
            if hadPermissionIssue {
                restrictedCount += 1
            }

            items.append(
                SystemDataItem(
                    category: spec.category,
                    locationPath: fullPath,
                    url: url,
                    sizeBytes: size,
                    measurability: wasTruncated ? .estimated : .measured,
                    explanation: spec.explanation,
                    recommendation: spec.recommendation,
                    potentialRisks: spec.potentialRisks,
                    isUserCleanable: spec.isUserCleanable && size > 0
                )
            )
        }

        let accountedBytes = max(totalMeasured, (knownScanBytes ?? 0) + totalMeasured / 2)
        let unindexedEstimate = max(0, volumeStats.usedBytes - min(volumeStats.usedBytes, accountedBytes))

        items.append(
            SystemDataItem(
                category: "APFS Snapshots, VM Swap & Unscanned System/Volume Space",
                locationPath: "/System/Volumes/VM & APFS Local Snapshots",
                url: nil,
                sizeBytes: unindexedEstimate,
                measurability: .estimated,
                explanation: "Estimated space used by Time Machine local snapshots, virtual memory swapfiles, Spotlight indexes, and volume directories outside the current user scan.",
                recommendation: .doNotModify,
                potentialRisks: "Managed automatically by macOS and APFS; macOS purges local snapshots automatically when disk space is needed.",
                isUserCleanable: false
            )
        )

        items.sort { ($0.sizeBytes ?? -1) > ($1.sizeBytes ?? -1) }

        return SystemDataReport(
            timestamp: Date(),
            items: items,
            totalMeasuredBytes: totalMeasured,
            estimatedUnindexedSystemBytes: unindexedEstimate,
            inaccessiblePathCount: restrictedCount
        )
    }

    private func measureDirectoryBytes(
        at directoryURL: URL,
        maxFiles: Int,
        maxSeconds: TimeInterval = 1.0,
        excludingSubpath: String? = nil
    ) async -> (Int64, Bool, Bool) {
        let keys: [URLResourceKey] = [
            .isSymbolicLinkKey,
            .totalFileAllocatedSizeKey,
            .fileAllocatedSizeKey,
            .fileSizeKey,
            .fileResourceIdentifierKey
        ]
        let keySet = Set(keys)
        var permissionErrorOccurred = false
        guard let enumerator = FileManager.default.enumerator(
            at: directoryURL,
            includingPropertiesForKeys: keys,
            options: [.skipsPackageDescendants],
            errorHandler: { _, _ in
                permissionErrorOccurred = true
                return true
            }
        ) else {
            return (0, true, false)
        }

        let excludedPrefix = excludingSubpath.map { $0 + "/" }
        let deadline = Date().addingTimeInterval(maxSeconds)
        var seenInodes: Set<AnyHashable> = []
        var total: Int64 = 0
        var count = 0
        var truncated = false
        while let fileURL = enumerator.nextObject() as? URL {
            if count % 400 == 0 {
                if Task.isCancelled {
                    truncated = true
                    break
                }
                if count > 0 && count % 1600 == 0 {
                    await Task.yield()
                }
            }
            if let excludingSubpath, let excludedPrefix {
                let p = StorageScanner.fastCleanPath(fileURL.path)
                if p == excludingSubpath || p.hasPrefix(excludedPrefix) {
                    enumerator.skipDescendants()
                    continue
                }
            }
            count += 1
            if count > maxFiles || (count % 512 == 0 && Date() >= deadline) {
                truncated = true
                break
            }
            guard let values = try? fileURL.resourceValues(forKeys: keySet),
                  values.isSymbolicLink != true else {
                continue
            }
            if let rawObj = values.fileResourceIdentifier as? NSObject {
                if !seenInodes.insert(AnyHashable(rawObj)).inserted {
                    continue
                }
            }
            let size = values.totalFileAllocatedSize ?? values.fileAllocatedSize ?? values.fileSize ?? 0
            total += Int64(size)
        }
        return (total, permissionErrorOccurred, truncated)
    }
}
